#pragma once
#include <Arduino.h>

// ── Общее состояние между задачами ────────────────────────────────────────
// Расписание, реле, кнопка, время и WiFi крутятся в отдельной задаче
// (controlTask, main.cpp), HTTP — в loopTask. Раньше всё было в одном
// loop(), и зависший HTTP-клиент (WebServer ждёт данные до 5 с на запрос)
// останавливал кнопку, реле и проверку расписания. Теперь веб держит этот
// мьютекс только пока обработчик меняет/читает состояние — ожидание клиента
// и отправка ответа идут без него. Рекурсивный: обработчики вызывают друг
// друга через общие хелперы.
void sys_lock();
void sys_unlock();

void        sys_setup();              // до всех остальных модулей (после logbuffer_init)
void        sys_setFsOk(bool ok);
bool        sys_fsOk();               // LittleFS смонтирован (mp3 + расписания доступны)
const char* sys_resetReason();        // причина последнего сброса, для /api/status
uint32_t    sys_crashCount();         // сколько раз ESP32 перезагружался из-за сбоя
