#pragma once
#include <Arduino.h>

// Физическая кнопка (BUTTON_PIN, config.h): ручной гонг, остановка звука и
// восстановление пароля. Опрос — из controlTask раз в 10 мс, без прерываний:
// дребезг контактов в ISR дал бы пачку ложных событий, а обработчик обязан
// быть неблокирующим (в controlTask висит watchdog).
//
// Семантика (все пороги — config.h):
//   • действие выбирается в момент СЫРОГО фронта нажатия по фактическому
//     состоянию звука и выполняется при отпускании; поэтому «зажал и держу»
//     не запускает гонг повторно, а «нажал во время гонга» не превращается в
//     запуск, даже если трек закончился в первые 50 мс дребезга;
//   • простой:  удержание < BUTTON_PLAY_HOLD_MS → игнорируется;
//               удержание ≥ BUTTON_PLAY_HOLD_MS → ручной гонг, ровно один раз;
//   • звук играет: удержание ≥ BUTTON_STOP_HOLD_MS → стоп (сразу, а если
//     отпускание пришлось ровно на порог — при отпускании), и это нажатие
//     больше ничего не делает;
//   • кнопка, зажатая при старте, не даёт ложного срабатывания;
//   • залипший контакт (≥ BUTTON_STUCK_MS) отменяет нажатие.
//
// Модуль не вызывает mp3_*/sched_*/web_* напрямую: всё, что нужно от
// прошивки, приходит тремя функциями (ButtonHooks). Это сохраняет единый путь
// ручного воспроизведения (/api/play) и позволяет прогонять логику на host с
// фальшивыми часами и фальшивым пином.

struct ButtonHooks {
    bool (*audioPlaying)();                              // mp3_isPlaying()
    void (*playManual)(uint8_t track, uint8_t vol, uint8_t loop);  // mp3_manualPlay()
    void (*stopAudio)();                                 // mp3_stop()
};

void button_setup(const ButtonHooks& hooks);  // после button_bootTick()/led_setup()
void button_loop();                           // из controlTask, под sys_lock

// ── Восстановление пароля при включении питания ────────────────────────────
// Отсчёт идёт от подачи питания, а не от конца инициализации: button_bootProbe()
// вызывается ПЕРВОЙ строкой setup() — настраивает вход (INPUT_PULLUP) и
// запоминает момент; gate крутится позже, после монтирования LittleFS, потому
// что сброс удаляет /auth.conf. Драйвер в main.cpp тикает каждые 10 мс и
// кормит watchdog; внутри модуля нет ни delay(), ни блокирующего I/O.
enum class BootGate : uint8_t {
    Settled,     // кнопка отпущена (или её нет): обычная загрузка продолжается
    Holding,     // ещё держат, но порог не достигнут — продолжать тикать
    ResetGrant,  // порог достигнут: вызвать web_resetAuth() (ровно один раз)
    WaitRelease, // сброс выдан, ждём стабильного отпускания перед обычной работой
};

void     button_bootProbe();            // ПЕРВАЯ строка setup(): pinMode + сэмпл
bool     button_bootHeldAtPowerOn();    // была ли кнопка зажата при включении
BootGate button_bootTick();             // продвинуть автомат (без задержек)
