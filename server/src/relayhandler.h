#pragma once
#include <Arduino.h>

// Реле питания внешнего усилителя / трансляционной линии (RELAY_PIN, config.h).
//
// Все запуски звука (расписание, веб-кнопка) идут через relay_play(), а не
// напрямую в mp3_play(): в режиме AUTO реле сначала включается, и звук
// стартует только через preMs — иначе усилитель ещё не вышел на режим и
// начало удара гонга срезается. Отсчёт прогрева идёт от момента включения
// реле: если оно уже включено (предвключение перед гонгом по расписанию,
// удержание после прошлого гонга, кнопка), звук ждёт только остаток или
// стартует сразу. После окончания трека реле держится holdMs
// (паузы между повторами loop не должны щёлкать реле) и отключается.
//
// Режимы:
//   AUTO — реле включено только на время гонга (по умолчанию)
//   ON   — всегда включено (ручное управление из веб-интерфейса)
//   OFF  — всегда выключено; внешний усилитель обесточен, PCM5102A звук
//          выдаёт, но слышно его только через усилитель с другим питанием
//
// Ручное включение (кнопка, удержание BUTTON_RELAY_HOLD_MS) — только в AUTO:
// реле держится включённым без звука, пока его не выключат кнопкой, веб-режимом
// или по истечении RELAY_MANUAL_MAX_MS. В NVS не пишется — после перезагрузки
// реле выключено.
//
// Вызывается из controlTask и веб-обработчиков — всегда под sys_lock()
// (sysstate.h), своих блокировок не нужно.

enum class RelayMode : uint8_t { AUTO, ON, OFF };

void   relay_setup();    // до первого relay_play(); настройки из NVS
void   relay_loop();     // каждый проход loop()

void   relay_play(uint8_t track, uint8_t vol, uint8_t loop);
void   relay_stop();     // остановить звук и отменить отложенный старт

// Предвключение (только AUTO): гонг по расписанию через msUntilGong — включить
// реле сейчас, чтобы к его времени усилитель уже прогрелся. Вызывается каждую
// секунду, пока до гонга <= preMs (+1 с на секундную точность часов);
// повторные вызовы только сдвигают срок удержания.
void   relay_prewarm(uint32_t msUntilGong);

bool   relay_setMode(RelayMode mode);
bool   relay_setTiming(uint32_t preMs, uint32_t holdMs);
bool   relay_parseMode(const String& s, RelayMode& out);

// false — режим не AUTO (ON/OFF из веба главнее кнопки), ничего не изменилось.
bool   relay_setManual(bool on);
bool   relay_isManual();

bool     relay_isOn();
bool     relay_isBusy();   // звук играет или ждёт окончания прогрева реле
uint32_t relay_preMs();
uint32_t relay_holdMs();
String   relay_toJSON();
