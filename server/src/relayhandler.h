#pragma once
#include <Arduino.h>

// Реле внешнего усилителя (RELAY_PIN, config.h). Коммутирует нагрузку вне
// платы (J3 → модуль реле 5 В с оптроном), НЕ питание MAX98357A: встроенный
// гонг звучит независимо от состояния реле.
//
// Все запуски и остановки звука идут через этот модуль, а не напрямую в
// mp3_start()/mp3_stop(): в AUTO реле включается до звука, и трек стартует
// только через preMs — иначе внешний усилитель ещё не вышел на режим и начало
// удара срезается. Отсчёт прогрева идёт от включения реле, поэтому если оно уже
// включено (предвключение к гонгу, удержание после прошлого трека, ручной
// режим), звук ждёт только остаток или стартует сразу.
//
// Режимы:
//   AUTO — реле включено только вокруг звука (по умолчанию), плюс ручной режим;
//   ON   — всегда включено (явная команда оператора, после перезагрузки НЕ
//          восстанавливается: безопасное состояние — OFF);
//   OFF  — всегда выключено; встроенный гонг при этом продолжает звучать.
//
// Состояния не взаимоисключающие: одновременно могут идти ручной режим,
// предвключение, воспроизведение и удержание — модуль сводит их к одному
// выходу «реле включено, пока есть причина». Наружу отдаётся производное
// состояние (state в relay_toJSON) только для индикации.
//
// Вызывается из controlTask и веб-обработчиков — всегда под sys_lock()
// (sysstate.h); своих блокировок не заводит. Единственный «дорогой» вызов —
// mp3_isPlaying() (audioMtx) — ограничен RELAY_POLL_PERIOD_MS.

enum class RelayMode : uint8_t { AUTO, ON, OFF };

void   relay_setup();    // до первого relay_play(); настройки из NVS
void   relay_loop();     // каждый проход controlTask

// true — звук начался сразу; false — трек поставлен в очередь на прогрев
// (расписание использует это, чтобы не отмечать событие прозвучавшим раньше
// фактического старта).
// outTag (необязательный) — уникальный тег запроса: по нему расписание
// отличает старт ИМЕННО этого гонга от чужого (кнопка/веб).
bool   relay_play(uint8_t track, uint8_t vol, uint8_t loop, uint32_t* outTag = nullptr);
void   relay_stop();     // стоп звука + отмена отложенного старта

// Предвключение (только AUTO): включить реле за msUntilGong до гонга, чтобы к
// его времени внешний усилитель был готов. Вызывается раз в секунду, пока до
// события <= preMs (+1 с на секундную точность часов).
void   relay_prewarm(uint32_t msUntilGong);

// Снять активное предвключение (цель исчезла/сменилась). Manual/play/hold не
// затрагиваются.
void   relay_cancelPrewarm();

// Отменить отложенный старт с указанным тегом (событие отключено/удалено/
// изменено). Manual и чужие запросы не затрагиваются.
void   relay_cancelPendingTag(uint32_t tag);

bool   relay_setMode(RelayMode mode);
bool   relay_setTiming(uint32_t pre, uint32_t hold);
// mode+pre+hold одной записью NVS (веб применяет комбинированный POST атомарно).
bool   relay_setConfig(RelayMode mode, uint32_t pre, uint32_t hold);
bool   relay_parseMode(const String& s, RelayMode& out);
RelayMode relay_currentMode();

// false — режим не AUTO (ON/OFF из веба главнее кнопки) или реле отключено.
bool   relay_setManual(bool on);
bool   relay_isManual();

bool     relay_isOn();
// Звук играет или ждёт прогрева. Состояние звука берётся из кэша relay_loop
// (не чаще RELAY_POLL_PERIOD_MS), а не из audioMtx на каждый вызов.
bool     relay_isBusy();
// true — тег принадлежит одному из последних реально стартовавших треков.
bool     relay_wasStartedTag(uint32_t tag);
bool     relay_isPendingStart();   // трек поставлен в очередь, но ещё не начался
// true — расписание было вынуждено ждать прогрева: гонг задержан (активная
// ошибка для LED) до фактического старта.
bool     relay_lateStartActive();
// Настройки реле не удалось записать в NVS (активная ошибка до успешной записи).
bool     relay_configError();
uint32_t relay_pendingTag();       // тег ожидающего трека (0 — очереди нет)
uint32_t relay_lastStartedTag();   // тег последнего РЕАЛЬНО стартовавшего трека
bool     relay_isEnabled();    // RELAY_PIN >= 0
uint32_t relay_preMs();
uint32_t relay_holdMs();
String   relay_toJSON();       // состояние и настройки для /api/relay и статуса
