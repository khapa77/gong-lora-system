#pragma once
#include <Arduino.h>

// Светодиод состояния (STATUS_LED_PIN, config.h). Модуль ничего не знает о
// расписании, курсах и файловой системе: «проблема» приходит извне одной
// функцией-предикатом (main.cpp), поэтому модуль компилируется и прогоняется
// host-тестами без schedule.cpp/LittleFS.
//
// Приоритет состояний (сверху — важнее):
//   1. AUTH_RESET   — ровный свет во время удержания кнопки при включении
//                     питания; реализуется прямым led_set(true) до старта
//                     controlTask, led_loop в это время ещё не работает.
//   2. BUTTON_READY — ровный свет, пока удержание ≥ BUTTON_PLAY_HOLD_MS:
//                     оператор должен видеть, что порог пройден, иначе он
//                     отпустит кнопку раньше. Индикация ошибки при этом
//                     приостанавливается ТОЛЬКО на время нажатия и
//                     возвращается сразу после отпускания.
//   3. ERROR        — мигание 5 Гц (LED_ERROR_PERIOD_MS): расписание не
//                     выполнится (нет времени / нет LittleFS / ошибка
//                     расписания / курс не опубликован).
//   4. NORMAL       — короткая вспышка LED_HEARTBEAT_ON_MS раз в
//                     LED_HEARTBEAT_MS.
//
// Все периоды считаются по накопленной разнице millis(), а не по абсолютному
// значению: переполнение счётчика (49.7 суток) не даёт ни скачка фазы, ни
// ложного срабатывания.

void led_setup();      // до button_bootBegin(): настраивает пин и гасит LED
void led_loop();       // из controlTask (10 мс), под sys_lock
void led_set(bool on); // прямое управление: удержание кнопки при включении

// Подсказка кнопки. Возврат в None — обязателен при отпускании и при отказе
// от нажатия (иначе светодиод останется включённым).
enum class LedHint : uint8_t { None, ButtonReady };
void led_hint(LedHint hint);

// Источник состояния ERROR. Не задан (nullptr) — модуль считает, что
// расписание не выполняется: индикация «проблема» безопаснее, чем ложное
// «всё хорошо». main.cpp ставит предикат до запуска controlTask.
void led_setProblemSource(bool (*source)());
