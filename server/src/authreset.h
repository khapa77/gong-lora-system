// курсы и их поколения, расписания, отметки миграции, RTC, громкость,
// шаблонный кэш и пользовательские файлы LittleFS. NVS не стирается целиком:
// это единственный способ не потерять привязку DS3231 и данные курса.
//
// Возвращает false, если очистка NVS не удалась; состояние файла не влияет на
// результат (его отсутствие — норма, а не ошибка). Вызывать только в
// loopTask или до старта семафора веба, как и прежний web_resetAuth().
