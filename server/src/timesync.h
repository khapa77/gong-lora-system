#pragma once
#include <Arduino.h>

// Источник системного времени выбирается автоматически, без переключателя в UI:
//
//   1. NTP — если STA подключён к сети с интернетом. Каждая успешная
//      синхронизация сразу записывается в DS3231.
//   2. DS3231 — при загрузке, и раз в RTC_RELOAD_MS, если NTP не отвечал
//      дольше NTP_STALE_MS (интернет пропал / его нет вовсе). Заодно
//      убирает дрейф кварца ESP32 (~1 с/сутки) на многодневном курсе.
//   3. Ручная установка из веба — когда нет ни интернета, ни живого DS3231.
//      Тоже пишется в DS3231; при появлении интернета NTP её перекроет.
//
// Системные часы хранят настоящее UTC, локальное время — через TZ (TIME_TZ).

void        time_setup();        // TZ + DS3231 → системные часы; до sched_setup()
void        time_loop();         // каждый проход loop()
void        time_startNtp();     // из wifi_loop() при подключении STA
bool        time_setManual(int year, int month, int day, int hour, int min);
const char* time_sourceName();   // "ntp" | "rtc" | "manual" | "none"
int32_t     time_ntpAgeSec();    // с последней NTP-синхронизации, -1 если не было
